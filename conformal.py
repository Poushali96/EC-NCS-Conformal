# ------------------------------------------------------

def local_variance(widths, k=20):
    w = np.sort(widths)
    return np.mean([np.var(w[i:i+k]) for i in range(len(w)-k)])

def run_experiment(X, y, name):
    print(f"\n===== Dataset: {name} =====")

    scaler = StandardScaler()
    X = scaler.fit_transform(X)

    X_tr, X_tmp, y_tr, y_tmp = train_test_split(
        X, y, test_size=0.4, random_state=42
    )
    X_cal, X_te, y_cal, y_te = train_test_split(
        X_tmp, y_tmp, test_size=0.5, random_state=42
    )

    model = RandomForestRegressor(
        n_estimators=200,
        max_depth=12,
        random_state=42,
        n_jobs=-1
    )
    model.fit(X_tr, y_tr)

    y_cal_pred = model.predict(X_cal)
    y_te_pred = model.predict(X_te)

    # ----------------------------------------------
    # Explanation proxy φ(x)
    # ----------------------------------------------
    feat_imp = model.feature_importances_
    phi_cal = np.linalg.norm(np.abs(X_cal) * feat_imp, axis=1)
    phi_te  = np.linalg.norm(np.abs(X_te) * feat_imp, axis=1)

    # dependence proxy
    corr = np.abs(np.corrcoef(X_tr.T))
    dep_cal = np.sum(np.abs(X_cal) @ corr, axis=1)
    dep_te  = np.sum(np.abs(X_te) @ corr, axis=1)

    # ----------------------------------------------
    # Nonconformity scores
    # ----------------------------------------------
    alpha = 0.1
    res_cal = np.abs(y_cal - y_cal_pred)

    # Standard CP
    q_std = np.quantile(res_cal, 1 - alpha)

    # EC-NCS (weighted)
    w_cal = 1 + dep_cal / np.mean(dep_cal)
    w_te  = 1 + dep_te / np.mean(dep_te)
    q_ec  = np.quantile(w_cal * res_cal, 1 - alpha)

    # EC-NCS (stratified)
    bins = np.quantile(phi_cal, [0, 0.33, 0.66, 1.0])
    strata_cal = np.digitize(phi_cal, bins[1:-1])
    strata_te  = np.digitize(phi_te, bins[1:-1])

    q_strata = {
        k: np.quantile(res_cal[strata_cal == k], 1 - alpha)
        for k in np.unique(strata_cal)
    }

    # Local CP baseline
    sigma_cal = np.std(X_cal, axis=1)
    sigma_te  = np.std(X_te, axis=1)
    q_local = np.quantile(res_cal / sigma_cal, 1 - alpha)

    # ----------------------------------------------
    # Prediction intervals
    # ----------------------------------------------
    intervals = {
        "Standard CP": (
            y_te_pred - q_std,
            y_te_pred + q_std
        ),
        "EC-NCS Weighted": (
            y_te_pred - q_ec / w_te,
            y_te_pred + q_ec / w_te
        ),
        "EC-NCS Stratified": (
            np.array([y_te_pred[i] - q_strata[strata_te[i]] for i in range(len(y_te))]),
            np.array([y_te_pred[i] + q_strata[strata_te[i]] for i in range(len(y_te))])
        ),
        "Local CP": (
            y_te_pred - q_local * sigma_te,
            y_te_pred + q_local * sigma_te
        )
    }

    # ----------------------------------------------
    # Metrics
    # ----------------------------------------------
    rows = []
    for name_m, (lo, hi) in intervals.items():
        width = hi - lo
        rows.append([
            name_m,
            np.mean((y_te >= lo) & (y_te <= hi)),
            np.mean(width),
            local_variance(width),
            spearmanr(phi_te, width)[0]
        ])

    df = pd.DataFrame(
        rows,
        columns=["Method", "Coverage", "Mean Width", "Width Variance", "Corr(φ, Width)"]
    )

    print(df.round(4))
    return df

