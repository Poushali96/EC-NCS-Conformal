import numpy as np
import pandas as pd
import time
import tracemalloc

from sklearn.datasets import fetch_california_housing, fetch_openml
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler

from sklearn.ensemble import RandomForestRegressor, GradientBoostingRegressor
from scipy.stats import spearmanr

np.random.seed(42)

# -------------------------
# Helper: stability metric
# -------------------------
def local_variance(widths, k=20):
    w = np.sort(np.asarray(widths))
    if len(w) <= k:
        return float(np.var(w))
    return float(np.mean([np.var(w[i:i+k]) for i in range(len(w)-k)]))

# -------------------------
# Helper: conditional coverage split
# -------------------------
def cond_coverage_by_phi(y_true, lo, hi, phi, q=0.5):
    phi = np.asarray(phi)
    thr = np.quantile(phi, q)
    low = phi <= thr
    high = phi > thr
    cov_low = float(np.mean((y_true[low] >= lo[low]) & (y_true[low] <= hi[low]))) if np.any(low) else np.nan
    cov_high = float(np.mean((y_true[high] >= lo[high]) & (y_true[high] <= hi[high]))) if np.any(high) else np.nan
    return cov_low, cov_high

# -------------------------
# Helper: time + peak memory wrapper
# -------------------------
def time_mem(fn, *args, **kwargs):
    tracemalloc.start()
    t0 = time.perf_counter()
    out = fn(*args, **kwargs)
    t1 = time.perf_counter()
    current, peak = tracemalloc.get_traced_memory()
    tracemalloc.stop()
    return out, (t1 - t0), (peak / (1024**2))

# -------------------------
# Core experiment per dataset
# -------------------------
def run_experiment(X, y, name, alpha=0.1):
    print(f"\n===== Dataset: {name} =====")

    # scale
    scaler = StandardScaler()
    X = scaler.fit_transform(X)

    # train/cal/test
    X_tr, X_tmp, y_tr, y_tmp = train_test_split(X, y, test_size=0.4, random_state=42)
    X_cal, X_te, y_cal, y_te = train_test_split(X_tmp, y_tmp, test_size=0.5, random_state=42)

    # -------------------------
    # Train base model f(x)
    # -------------------------
    def train_rf():
        m = RandomForestRegressor(n_estimators=200, max_depth=12, random_state=42, n_jobs=-1)
        m.fit(X_tr, y_tr)
        return m

    model, t_train, mem_train = time_mem(train_rf)

    y_cal_pred = model.predict(X_cal)
    y_te_pred  = model.predict(X_te)

    # -------------------------
    # Explanation proxies φ(x)
    # -------------------------
    # φ_strength(x) = || |x| ⊙ feature_importance ||
    feat_imp = model.feature_importances_
    phi_cal = np.linalg.norm(np.abs(X_cal) * feat_imp, axis=1)
    phi_te  = np.linalg.norm(np.abs(X_te)  * feat_imp, axis=1)

    # dependence proxy dep(x) = sum(|x| @ |Corr|)
    corr = np.abs(np.corrcoef(X_tr.T))
    dep_cal = np.sum(np.abs(X_cal) @ corr, axis=1)
    dep_te  = np.sum(np.abs(X_te)  @ corr, axis=1)

    # -------------------------
    # Base residual nonconformity
    # -------------------------
    res_cal = np.abs(y_cal - y_cal_pred)
    q_std = np.quantile(res_cal, 1 - alpha)

    # -------------------------
    # Methods produce (lo, hi)
    # Each method timed separately for fairness
    # -------------------------
    def standard_cp():
        lo = y_te_pred - q_std
        hi = y_te_pred + q_std
        return lo, hi

    def naive_cp():
        # same as standard (kept to show "no extra compute")
        lo = y_te_pred - q_std
        hi = y_te_pred + q_std
        return lo, hi

    def local_cp():
        sigma_cal = np.std(X_cal, axis=1) + 1e-12
        sigma_te  = np.std(X_te, axis=1)  + 1e-12
        q_local = np.quantile(res_cal / sigma_cal, 1 - alpha)
        lo = y_te_pred - q_local * sigma_te
        hi = y_te_pred + q_local * sigma_te
        return lo, hi

    def ecncs_weighted():
        w_cal = 1 + dep_cal / np.mean(dep_cal)
        w_te  = 1 + dep_te  / np.mean(dep_te)
        q_ec = np.quantile(w_cal * res_cal, 1 - alpha)
        lo = y_te_pred - q_ec / w_te
        hi = y_te_pred + q_ec / w_te
        return lo, hi

    def ecncs_stratified():
        # stratify by phi on calibration
        bins = np.quantile(phi_cal, [0, 0.33, 0.66, 1.0])
        strata_cal = np.digitize(phi_cal, bins[1:-1])
        strata_te  = np.digitize(phi_te,  bins[1:-1])

        q_strata = {k: np.quantile(res_cal[strata_cal == k], 1 - alpha) for k in np.unique(strata_cal)}

        lo = np.empty_like(y_te_pred, dtype=float)
        hi = np.empty_like(y_te_pred, dtype=float)
        for i in range(len(y_te_pred)):
            qk = q_strata[strata_te[i]]
            lo[i] = y_te_pred[i] - qk
            hi[i] = y_te_pred[i] + qk
        return lo, hi

    # -------------------------
    # CQR baseline (Conformalized Quantile Regression)
    # -------------------------
    # Fit two quantile models: lower (α/2) and upper (1-α/2), then conformalize
    def cqr_conformal():
        q_lo = alpha / 2.0
        q_hi = 1 - alpha / 2.0

        # GradientBoosting quantile models are deterministic and lightweight
        m_lo = GradientBoostingRegressor(loss="quantile", alpha=q_lo, random_state=42)
        m_hi = GradientBoostingRegressor(loss="quantile", alpha=q_hi, random_state=42)

        m_lo.fit(X_tr, y_tr)
        m_hi.fit(X_tr, y_tr)

        lo_cal = m_lo.predict(X_cal)
        hi_cal = m_hi.predict(X_cal)

        # conformalize by calibration nonconformity for intervals
        # score_i = max(lo_cal - y_cal, y_cal - hi_cal, 0)
        s_cal = np.maximum(lo_cal - y_cal, y_cal - hi_cal)
        q = np.quantile(s_cal, 1 - alpha)

        lo_te = m_lo.predict(X_te) - q
        hi_te = m_hi.predict(X_te) + q
        return lo_te, hi_te

    methods = {
        "Standard CP": standard_cp,
        "Naive CP": naive_cp,
        "Local CP": local_cp,
        "EC-NCS Weighted": ecncs_weighted,
        "EC-NCS Stratified": ecncs_stratified,
        "CQR (baseline)": cqr_conformal,
    }

    rows = []
    for mname, fn in methods.items():
        (lo, hi), t_m, mem_m = time_mem(fn)

        width = hi - lo
        coverage = float(np.mean((y_te >= lo) & (y_te <= hi)))
        mean_w = float(np.mean(width))
        var_w = local_variance(width)
        corr_phi = float(spearmanr(phi_te, width)[0])

        cov_low, cov_high = cond_coverage_by_phi(y_te, lo, hi, phi_te, q=0.5)

        rows.append({
            "Method": mname,
            "Coverage": coverage,
            "Mean Width": mean_w,
            "Width Variance": var_w,
            "Corr(φ, Width)": corr_phi,
            "Cond Coverage (Low φ)": cov_low,
            "Cond Coverage (High φ)": cov_high,
            "Time (s)": t_m,
            "Peak Mem (MB)": mem_m,
        })

    df = pd.DataFrame(rows)
    df.insert(0, "Dataset", name)

    # Print compact summary
    show_cols = ["Method", "Coverage", "Mean Width", "Width Variance", "Corr(φ, Width)",
                 "Cond Coverage (Low φ)", "Cond Coverage (High φ)", "Time (s)", "Peak Mem (MB)"]
    print(df[show_cols].round(4))

    # Print training cost separately (useful for paper)
    print(f"Training RF time (s): {t_train:.4f} | Training peak mem (MB): {mem_train:.2f}")

    return df

