def binned_curve(x, y, n_bins=10):
    x = np.asarray(x)
    y = np.asarray(y)
    qs = np.quantile(x, np.linspace(0, 1, n_bins + 1))
    xs, ys = [], []
    for k in range(n_bins):
        idx = (x >= qs[k]) & (x <= qs[k+1])
        if np.sum(idx) == 0:
            continue
        xs.append(float(np.mean(x[idx])))
        ys.append(float(np.mean(y[idx])))
    return np.array(xs), np.array(ys)

