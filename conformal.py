def local_variance(widths, k=20):
    w = np.sort(widths)
    if len(w) <= k:
        return 0.0
    return np.mean([np.var(w[i:i+k]) for i in range(len(w)-k)])

def bootstrap_metric(y_te, lo, hi, metric_func, n_boot=200):
    metrics = []
    n = len(y_te)
    for _ in range(n_boot):
        idx = np.random.choice(n, n, replace=True)
        metrics.append(metric_func(y_te[idx], lo[idx], hi[idx]))
    return np.std(metrics)

def coverage_func(y, lo, hi):
    return np.mean((y >= lo) & (y <= hi))

def mean_width_func(_, lo, hi):
    return np.mean(hi - lo)

def run_experiment(X, y, name, plot_dir='plots'):
    start_time = time.time()
    print(f"\n===== Dataset: {name} =====")
    scaler = StandardScaler()
    X = scaler.fit_transform(X)
    X_tr, X_tmp, y_tr, y_tmp = train_test_split(X, y, test_size=0.4, random_state=42)
    X_cal, X_te, y_cal, y_te = train_test_split(X_tmp, y_tmp, test_size=0.5, random_state=42)

    model = RandomForestRegressor(n_estimators=200, max_depth=12, random_state=42, n_jobs=-1)
    model.fit(X_tr, y_tr)
    y_cal_pred = model.predict(X_cal)
    y_te_pred = model.predict(X_te)

    # Proxies
    feat_imp = model.feature_importances_
    phi_cal = np.linalg.norm(np.abs(X_cal) * feat_imp, axis=1)
    phi_te  = np.linalg.norm(np.abs(X_te)  * feat_imp, axis=1)

    corr = np.abs(np.corrcoef(X_tr.T))
    dep_cal = np.sum(np.abs(X_cal) @ corr, axis=1)
    dep_te  = np.sum(np.abs(X_te)  @ corr, axis=1)

    # Nonconformity
    alpha = 0.1
    res_cal = np.abs(y_cal - y_cal_pred)

    q_std = np.quantile(res_cal, 1 - alpha)

    w_cal = 1 + dep_cal / np.mean(dep_cal)
    w_te  = 1 + dep_te  / np.mean(dep_te)
    q_ec  = np.quantile(w_cal * res_cal, 1 - alpha)

    bins = np.quantile(phi_cal, [0, 0.33, 0.66, 1.0])
    strata_cal = np.digitize(phi_cal, bins[1:-1])
    strata_te  = np.digitize(phi_te,  bins[1:-1])
    q_strata = {k: np.quantile(res_cal[strata_cal == k], 1 - alpha)
                for k in np.unique(strata_cal) if np.sum(strata_cal == k) > 5}

    sigma_cal = np.std(X_cal, axis=1) + 1e-8
    sigma_te  = np.std(X_te,  axis=1) + 1e-8
    q_local   = np.quantile(res_cal / sigma_cal, 1 - alpha)

    q_naive = q_std  # same as standard in this setup

    # Intervals
    intervals = {
        "Standard CP": (y_te_pred - q_std, y_te_pred + q_std),
        "EC-NCS Weighted": (y_te_pred - q_ec / w_te, y_te_pred + q_ec / w_te),
        "EC-NCS Stratified": (
            y_te_pred - np.array([q_strata.get(s, q_std) for s in strata_te]),
            y_te_pred + np.array([q_strata.get(s, q_std) for s in strata_te])
        ),
        "Local CP": (y_te_pred - q_local * sigma_te, y_te_pred + q_local * sigma_te),
        "Naive CP": (y_te_pred - q_naive, y_te_pred + q_naive),
    }

    # Metrics
    rows = []
    widths_dict = {}
    for name_m, (lo, hi) in intervals.items():
        width = hi - lo
        widths_dict[name_m] = width

        coverage   = np.mean((y_te >= lo) & (y_te <= hi))
        mean_width = np.mean(width)
        width_var  = local_variance(width)
        corr_phi   = spearmanr(phi_te, width)[0]

        med_phi = np.median(phi_te)
        low_mask  = phi_te < med_phi
        high_mask = phi_te >= med_phi
        cc_low  = np.mean((y_te[low_mask]  >= lo[low_mask])  & (y_te[low_mask]  <= hi[low_mask])) if low_mask.sum()  > 0 else np.nan
        cc_high = np.mean((y_te[high_mask] >= lo[high_mask]) & (y_te[high_mask] <= hi[high_mask])) if high_mask.sum() > 0 else np.nan

        cov_se  = bootstrap_metric(y_te, lo, hi, coverage_func)
        w_se    = bootstrap_metric(y_te, lo, hi, mean_width_func)

        efficiency = mean_width * (1 - abs(coverage - 0.9))

        rows.append([
            name_m, coverage, cov_se, mean_width, w_se, width_var, corr_phi,
            cc_low, cc_high, efficiency
        ])

    df = pd.DataFrame(rows, columns=[
        "Method", "Coverage", "Cov SE", "Mean Width", "Width SE", "Width Variance",
        "Corr(φ, Width)", "Cond Coverage (Low φ)", "Cond Coverage (High φ)", "Efficiency"
    ])
    print(df.round(4))

    runtime = time.time() - start_time
    print(f"Runtime: {runtime:.2f} s")

    # Binned conditional coverage
    n_bins = 8
    phi_bins = pd.qcut(phi_te, q=n_bins, labels=False, duplicates='drop')
    bin_coverages = {}
    for name_m, (lo, hi) in intervals.items():
        cov_per_bin = []
        for b in range(n_bins):
            mask = (phi_bins == b)
            if mask.sum() >= 10:
                cov_per_bin.append(np.mean((y_te[mask] >= lo[mask]) & (y_te[mask] <= hi[mask])))
            else:
                cov_per_bin.append(np.nan)
        bin_coverages[name_m] = cov_per_bin

    # Visualizations
    os.makedirs(plot_dir, exist_ok=True)

    # 1. Metrics bar
    metrics_to_plot = ["Coverage", "Mean Width", "Efficiency", "Corr(φ, Width)"]
    df_melt = df.melt(id_vars="Method", value_vars=metrics_to_plot)
    plt.figure(figsize=(14, 7))
    sns.barplot(data=df_melt, x="variable", y="value", hue="Method", palette=METHOD_COLORS, edgecolor="black")
    plt.axhline(0.90, color="black", ls="--", alpha=0.7, label="Target 90%") if "Coverage" in metrics_to_plot else None
    plt.title(f"Performance – {name}", fontsize=16)
    plt.legend(bbox_to_anchor=(1.02, 1), loc='upper left')
    plt.tight_layout()
    plt.savefig(f"{plot_dir}/{name}_metrics_bar.png", dpi=300, bbox_inches="tight")
    plt.close()

    # 2. Width violin + strip
    widths_melt = pd.DataFrame(widths_dict).melt(var_name="Method", value_name="Width")
    plt.figure(figsize=(12, 6))
    sns.violinplot(data=widths_melt, x="Method", y="Width", palette=METHOD_COLORS, inner=None, linewidth=1.2)
    sns.stripplot(data=widths_melt, x="Method", y="Width", color="black", alpha=0.4, size=3, jitter=0.2)
    if name == "Concrete Strength":
        plt.yscale('log')
    plt.title(f"Interval Widths – {name}", fontsize=16)
    plt.xticks(rotation=30)
    plt.tight_layout()
    plt.savefig(f"{plot_dir}/{name}_width_violin.png", dpi=300)
    plt.close()

    # 3. Width vs φ scatter (one figure with subplots)
    fig, axes = plt.subplots(1, len(intervals), figsize=(4.5*len(intervals), 5), sharey=True)
    for idx, (method, width) in enumerate(widths_dict.items()):
        axes[idx].scatter(phi_te, width, alpha=0.4, s=20)
        axes[idx].set_title(method, fontsize=11)
        axes[idx].set_xlabel("φ(x)")
        if idx == 0:
            axes[idx].set_ylabel("Width")
    fig.suptitle(f"Width vs Explanation Strength – {name}", y=0.98)
    plt.tight_layout()
    plt.savefig(f"{plot_dir}/{name}_phi_width_scatter.png", dpi=300)
    plt.close()

    # 4. Binned conditional coverage
    plt.figure(figsize=(12, 6))
    for method, covs in bin_coverages.items():
        valid = ~np.isnan(covs)
        if valid.sum() > 1:
            plt.plot(np.arange(1, n_bins+1)[valid], np.array(covs)[valid], marker="o", label=method, color=METHOD_COLORS[method])
    plt.axhline(0.90, color="black", ls="--", label="Target")
    plt.xlabel("Difficulty bin (φ quantile) 1=easiest → 8=hardest")
    plt.ylabel("Coverage")
    plt.title(f"Adaptive Coverage – {name}")
    plt.legend(bbox_to_anchor=(1.02,1))
    plt.tight_layout()
    plt.savefig(f"{plot_dir}/{name}_binned_coverage.png", dpi=300)
    plt.close()

    # Optional: True vs Predicted scatter with example intervals (Standard CP)
    plt.figure(figsize=(8, 8))
    plt.scatter(y_te, y_te_pred, alpha=0.5, s=25, label="Predictions")
    lo_std, hi_std = intervals["Standard CP"]
    sort_idx = np.argsort(y_te)
    plt.fill_between(y_te[sort_idx], lo_std[sort_idx], hi_std[sort_idx],
                     alpha=0.15, color=METHOD_COLORS["Standard CP"], label="Standard CP 90% band")
    plt.plot([y.min(), y.max()], [y.min(), y.max()], 'k--', lw=1.5, label="Perfect")
    plt.xlabel("True value")
    plt.ylabel("Predicted value")
    plt.title(f"True vs Predicted with Std CP intervals – {name}")
    plt.legend()
    plt.tight_layout()
    plt.savefig(f"{plot_dir}/{name}_true_vs_pred.png", dpi=300)
    plt.close()

    return df, phi_te, widths_dict, runtime, bin_coverages

