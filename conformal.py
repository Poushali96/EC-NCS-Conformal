w_test = 1.0 + dep_test / np.mean(dep_test)

res_ec_cal = w_cal * res_cal

# -------------------------------
# 5. Quantiles
# -------------------------------

q_std = np.quantile(res_cal, 1 - alpha)
q_ec = np.quantile(res_ec_cal, 1 - alpha)

