# ======================================================
# 5) Matched-residual pairs construction
#    For each residual bin, pair LOW-φ with HIGH-φ points
#    This maximizes explanation difference while controlling residual.
# ======================================================
def matched_pairs_by_bins(residuals, phi, n_bins=20, pairs_per_bin=50, seed=42):
    rng = np.random.default_rng(seed)
    residuals = np.asarray(residuals)
    phi = np.asarray(phi)

    edges = np.quantile(residuals, np.linspace(0, 1, n_bins + 1))
    pairs = []  # list of (i, j) indices

    for b in range(n_bins):
        in_bin = np.where((residuals >= edges[b]) & (residuals <= edges[b+1]))[0]
        if len(in_bin) < 10:
            continue

        # Split into low/high phi groups inside the bin
        phi_bin = phi[in_bin]
        thr = np.quantile(phi_bin, 0.5)
        low = in_bin[phi_bin <= thr]
        high = in_bin[phi_bin > thr]

        if len(low) == 0 or len(high) == 0:
            continue

        # Sample pairs: pick i from low and j from high
        # This keeps residuals similar (same bin) and boosts phi difference.
        m = min(pairs_per_bin, len(low), len(high))
        low_s  = rng.choice(low, size=m, replace=False) if len(low) >= m else rng.choice(low, size=m, replace=True)
        high_s = rng.choice(high, size=m, replace=False) if len(high) >= m else rng.choice(high, size=m, replace=True)

        for i, j in zip(low_s, high_s):
            pairs.append((int(i), int(j)))

    return pairs, edges

